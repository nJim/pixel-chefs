// Scrapes the Four Kitchens team page and writes:
//   shared/team.ts          roster (opaque id, name, title) shared by server + client
//   client/chef-images.ts   id -> square JPEG data URI, bundled with the client
// Run with: npm run fetch-team
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { parse } from "node-html-parser";
import sharp from "sharp";

const TEAM_URL = "https://www.fourkitchens.com/team/";
const SIZE = 320;

// Opaque ids keep names out of image keys and network payloads.
const opaqueId = (name) => createHash("sha256").update(`pixel-chefs:${name}`).digest("hex").slice(0, 8);

// Strip the ShortPixel CDN prefix to get the original upload.
const originalUrl = (src) => src.replace(/^https:\/\/sp-ao\.shortpixel\.ai\/client\/[^/]+\//, "");

// Optional, untracked list of names (one per line) to leave out of the roster.
const EXCLUDE_FILE = ".roster-exclude";
const excluded = new Set(
  (await readFile(EXCLUDE_FILE, "utf8").catch(() => ""))
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#")),
);

const html = await (await fetch(TEAM_URL)).text();
const cards = parse(html).querySelectorAll(".team_card");

const team = [];
const images = {};

for (const card of cards) {
  const name = card.querySelector("h4")?.text.trim();
  const title = card.querySelector(".job_title")?.text.trim() ?? "";
  const src = card.querySelector("img.lazyload")?.getAttribute("data-src");
  if (!name || !src || excluded.has(name)) continue;

  const res = await fetch(originalUrl(src));
  if (!res.ok) throw new Error(`Failed to download ${name}: ${res.status}`);
  const jpeg = await sharp(Buffer.from(await res.arrayBuffer()))
    .resize(SIZE, SIZE, { fit: "cover", position: "attention" })
    .jpeg({ quality: 78 })
    .toBuffer();

  const id = opaqueId(name);
  team.push({ id, name, title });
  images[id] = `data:image/jpeg;base64,${jpeg.toString("base64")}`;
  console.log(`✓ ${name} (${(jpeg.length / 1024).toFixed(1)} KB)`);
}

if (team.length < 4) throw new Error(`Only found ${team.length} team members; the page markup may have changed.`);

await writeFile(
  "shared/team.ts",
  `// Generated by scripts/fetch-team.mjs. Do not edit by hand.
export type Chef = { id: string; name: string; title: string };

export const TEAM: Chef[] = ${JSON.stringify(team, null, 2)};

export const CHEFS_BY_ID: Record<string, Chef> = Object.fromEntries(TEAM.map((chef) => [chef.id, chef]));
`,
);

await writeFile(
  "client/chef-images.ts",
  `// Generated by scripts/fetch-team.mjs. Do not edit by hand.
export const CHEF_IMAGES: Record<string, string> = ${JSON.stringify(images, null, 2)};
`,
);

console.log(`\nWrote ${team.length} chefs.`);
